// Helper function to normalize Bulgarian words (remove punctuation, lowercase)
const normalizeWord = (word: string): string => {
  return word.toLowerCase().replace(/[.,!?;:'"()]/g, '').trim();
};

export const getWordFrequency = (word: string): FrequencyLevel => {
  const normalized = normalizeWord(word);
  return frequencyMap[normalized] || 5; // Default to rare if not in list
};

export const getFrequencyInfo = (word: string): FrequencyInfo => {
  const level = getWordFrequency(word);
  return FREQUENCY_INFO[level];
};

// Get frequency bar width as percentage
export const getFrequencyBarWidth = (level: FrequencyLevel): number => {
  return ((6 - level) / 5) * 100; // Level 1 = 100%, Level 5 = 20%
};
